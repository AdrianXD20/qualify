-- Aceptación de la cita por ambas partes.
-- El familiar que crea el servicio se considera que ya aceptó.
ALTER TABLE servicios
  ADD COLUMN IF NOT EXISTS aceptado_por_familiar boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS aceptado_por_cuidador boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS aceptado_familiar_en timestamptz DEFAULT now(),
  ADD COLUMN IF NOT EXISTS aceptado_cuidador_en timestamptz;

-- Mensajes del chat asociados a un servicio.
CREATE TABLE IF NOT EXISTS mensajes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  servicio_id integer NOT NULL REFERENCES servicios(id) ON DELETE CASCADE,
  emisor_id integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  contenido text NOT NULL CHECK (char_length(contenido) BETWEEN 1 AND 2000),
  creado_en timestamptz NOT NULL DEFAULT now(),
  leido_en timestamptz
);

CREATE INDEX IF NOT EXISTS idx_mensajes_servicio
  ON mensajes (servicio_id, id);

-- Sin políticas: solo el backend (service role) puede leer/escribir mensajes.
ALTER TABLE mensajes ENABLE ROW LEVEL SECURITY;
