-- ============================================================
-- 004: consultas privadas entre familiares y cuidadores
-- Ejecutar en Supabase > SQL Editor para habilitar el chat previo
-- a la contratación.
-- ============================================================

CREATE TABLE IF NOT EXISTS consultas_cuidadores (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  familiar_id integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  cuidador_id integer NOT NULL REFERENCES cuidadores(id) ON DELETE CASCADE,
  creado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  UNIQUE (familiar_id, cuidador_id)
);

CREATE INDEX IF NOT EXISTS idx_consultas_cuidadores_familiar
  ON consultas_cuidadores (familiar_id, actualizado_en DESC);

CREATE INDEX IF NOT EXISTS idx_consultas_cuidadores_cuidador
  ON consultas_cuidadores (cuidador_id, actualizado_en DESC);

CREATE TABLE IF NOT EXISTS mensajes_consulta (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  consulta_id integer NOT NULL REFERENCES consultas_cuidadores(id) ON DELETE CASCADE,
  emisor_id integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  contenido text NOT NULL CHECK (char_length(contenido) BETWEEN 1 AND 2000),
  creado_en timestamptz NOT NULL DEFAULT now(),
  leido_en timestamptz
);

CREATE INDEX IF NOT EXISTS idx_mensajes_consulta
  ON mensajes_consulta (consulta_id, id);

ALTER TABLE consultas_cuidadores ENABLE ROW LEVEL SECURITY;
ALTER TABLE mensajes_consulta ENABLE ROW LEVEL SECURITY;
